DEFAULT_STRATEGY = "speed"
# Неизвестное и старое значение "whitelist" падает на безопасный эксплуатационный
# дефолт: живые измерения важнее статической географии.


def norm(cc):
    return (str(cc or "").strip().lower() or None)


def strategy(cfg=None):
    """id действующей стратегии. Неизвестное/пустое значение -> по умолчанию."""
    s = norm(((cfg or {}).get("countries") or {}).get("strategy"))
    return s if s in STRATEGIES else DEFAULT_STRATEGY


def strategy_info(cfg=None, name=None):
    """Описание стратегии (с полем id): для панели, журнала и объяснений."""
    st = name if name in STRATEGIES else strategy(cfg)
    return dict(STRATEGIES[st], id=st)


def preference_order(cfg=None):
    """ВНУТРЕННИЙ порядок предпочтения стран (ближние к РФ первыми) без чёрного списка.

    Это не пользовательский «белый список» (его больше нет — приёмка №7), а константа
    системы для tie-break'ов ранжирования: при равном рейтинге раньше идёт страна,
    что ближе. Конфиг-ключ countries.whitelist больше не читается."""
    # ленивый импорт: модуль остаётся независимым (см. шапку), а список стран
    # не размножается ещё одной копией
    from providers.base import DEFAULT_COUNTRY_ORDER
    bl = blacklist(cfg)
    return [c for c in (norm(x) for x in DEFAULT_COUNTRY_ORDER) if c and c not in bl]


def blacklist(cfg=None):
    """Чёрный список: код + необязательное расширение из конфига. Только РАСШИРЯЕТ."""
    extra = ((cfg or {}).get("countries") or {}).get("blacklist") or []
    return set(BLACKLIST_CC) | {c for c in (norm(x) for x in extra) if c}


def is_blocked(cc, cfg=None):
    c = norm(cc)
    return bool(c) and c in blacklist(cfg)


def reputation(cc, geo_agree=True, cfg=None):
    """Репутация САМОЙ страны: None — запрещена, иначе число (больше = меньше проблем).

    От стратегии не зависит: рискованная страна остаётся рискованной, что бы админ
    ни выбрал — стратегия решает лишь, насколько сильно это влияет на выбор (rating).
    geo_agree=False — базы geoip разошлись в определении страны этого IP.
    Неизвестная страна (None) — нейтральна: незнание не повод ни блокировать,
    ни поощрять.
    """
    c = norm(cc)
    if c and c in blacklist(cfg):
        return None
    if c is None:
        base = RATING_NEUTRAL
    elif c in TRUSTED_CC:
        base = RATING_TRUSTED
    elif c in GOOD_CC:
        base = RATING_GOOD
    elif c in LOW_TRUST_CC:
        base = RATING_LOW
    else:
        base = RATING_NEUTRAL
    return base + (0 if geo_agree else GEO_MISMATCH_PENALTY)


def rating(cc, geo_agree=True, cfg=None):
    """Вклад страны в выбор при действующей стратегии: None — запрещена.

    Это репутация (внутренний рейтинг системы), помноженная на вес стратегии
    (у «скорости» вес 0 — страна не влияет ни на порядок, ни на оценку). Именно
    это число складывает probe.score и сортирует rank/rank_candidates.
    """
    rep = reputation(cc, geo_agree, cfg)
    if rep is None:
        return None
    st = STRATEGIES[strategy(cfg)]
    return round(rep * st["weight"], 1)


def auto_allowed(cc, geo_agree=True, cfg=None):
    """Может ли автоматика САМА купить прокси в этой стране.

    Человек — шире: вручную можно любую страну, кроме чёрного списка (is_blocked)."""
    rep = reputation(cc, geo_agree, cfg)
    if rep is None:
        return False                                   # чёрный список — никогда
    st = STRATEGIES[strategy(cfg)]
    if st["auto_gate"] and rep < MIN_AUTO_RATING:
        return False                                   # рискованную — только руками
    return True


def tier(cc, geo_agree=True, cfg=None):
    """Короткая метка для интерфейса и журнала (репутация страны, без стратегии)."""
    r = reputation(cc, geo_agree, cfg)
    if r is None:
        return "blocked"
    if not geo_agree:
        return "disputed"
    if r >= RATING_TRUSTED:
        return "trusted"
    if r >= RATING_GOOD:
        return "good"
    if r <= RATING_LOW:
        return "risky"
    return "neutral"


def explain(cc, geo_agree=True, cfg=None):
    """Человеческое объяснение — идёт в подсказку панели и в причину отказа."""
    c = norm(cc)
    t = tier(c, geo_agree, cfg)
    if t == "blocked":
        return "страна в чёрном списке — не покупаем и не используем никогда"
    if t == "disputed":
        return ("geoip-базы расходятся в определении страны этого IP — для сайтов "
                "«страна скачет», это лишние капчи и проверки оплаты")
    if t == "trusted":
        return "надёжная страна выхода: Европа/США — минимум лишних проверок"
    if t == "good":
        return "нормальная страна выхода, но дальше от РФ — выше задержка"
    if t == "risky":
        return ("страна с высоким риском отказов: банки, платёжки и магазины "
                "часто требуют доп. подтверждения или блокируют оплату")
    return "нейтральная страна: явных проблем не известно"


def rank(candidates, cfg=None):
    """Отсортировать коды стран по убыванию оценки; запрещённые — выбросить.

    Порядок внутри одной оценки сохраняется входной (у вызывающего он осмысленный:
    например, «предпочитаемые» страны из конфига идут по возрастанию задержки).
    """
    out = []
    for i, cc in enumerate(candidates or []):
        c = norm(cc)
        r = rating(c, True, cfg)
        if r is None:
            continue
        out.append((-r, i, c))
    return [c for _, _, c in sorted(out)]
