RATING_TRUSTED = 25
RATING_GOOD = 12
RATING_NEUTRAL = 0
RATING_LOW = -25
GEO_MISMATCH_PENALTY = -20   # geoip-базы разошлись: для сайтов «страна скачет»
MIN_AUTO_RATING = 0          # ниже — автоматика сама не покупает (человек может)

# ── 3. Стратегия: КАК сильно страна влияет на выбор (настройка админа, 17.08) ──
#
# До 17.08 политика была одна и зашита в код — «репутация решает». Она хороша по
# умолчанию, но подходит не всем: кому-то нужен стабильно европейский выход (банк-
# клиент, рабочие сервисы), а кому-то важнее самый быстрый канал, и он готов мириться
# с капчами. Поэтому правило вынесено в `config['countries']['strategy']`.
#
# ЧЁРНЫЙ СПИСОК ВНЕ ВЫБОРА: ни одна стратегия не разрешает ru/ua/by — это по-прежнему
# предохранитель в коде, а не настройка (§6.1).
#
# Стратегия влияет ровно на три решения и больше ни на что:
#   1) где автоматике МОЖНО покупать       -> auto_allowed / money.buy_candidates
#   2) в каком порядке перебирать пул      -> states.rank_candidates
#   3) какой вес у страны в оценке пробы   -> probe.score (через rating)
#
# Поля стратегии:
#   weight         — множитель репутации (и штрафа за расхождение geoip) в оценке.
#                    0.0 = страна не влияет на выбор вообще, решают замеры;
#   country_first  — страна как ПЕРВИЧНЫЙ ключ сортировки кандидатов (иначе репутация
#                    просто складывается с результатом замеров, и быстрый прокси
#                    рискованной страны может обогнать медленный надёжной);
#   auto_gate      — автоматика сама покупает только страны с репутацией >= 0
#                    (рискованные остаются доступны человеку вручную).
#
# Пользовательского «белого списка» стран больше нет (решение владельца, приёмка №7
# 17.08): страны оценивает ВНУТРЕННИЙ рейтинг системы (reputation/rating ниже), а
# вручную человек может купить любую страну, кроме чёрного списка. Порядок «ближние
# первыми» остался внутренней константой ранжирования — providers.base.DEFAULT_COUNTRY_ORDER.
